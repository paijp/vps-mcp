#!/bin/sh
# https://github.com/paijp/vps-subdomain-mcp
#
# Register, update or remove one DNS zone (multidomain edition).
#
#   sh scripts/zone.sh apply  <domain> <records-file>   (make <domain>.dnsdone)
#   sh scripts/zone.sh remove <domain>                  (make <domain>.undns)
#
# apply builds the zone from host/bind/zone.tmpl (SOA, NS, @/*/ns1 A, SPF,
# DMARC — host-managed), the domain's DKIM record, and the records file
# (operator-managed: MX, TXT, CNAME, ...). The records file is checked first:
# no SOA/NS, no $-directives, no owner-less lines, nothing under
# mail._domainkey, and no A/AAAA/CNAME on a name a running container serves.
# The result must pass named-checkzone; otherwise the live zone is left as is.
#
# On first apply it also creates the DKIM key, the opendkim KeyTable/
# SigningTable lines, the BIND zone statement, and adds the domain to
# /etc/vps-mcp/domains (read by the proxies, no restart needed).
set -eu

die() { echo "Error: $*" >&2; exit 1; }

[ -f /etc/vps-mcp/host.env ] || die "/etc/vps-mcp/host.env not found — run make <IP>.setupdone first."
. /etc/vps-mcp/host.env
: "${IP:?IP missing in host.env}"
: "${BIND_ZONE_DIR:?BIND_ZONE_DIR missing in host.env}"
: "${BIND_CONF:?BIND_CONF missing in host.env}"

MODE=${1:-}
D=$(printf '%s' "${2:-}" | tr 'A-Z' 'a-z')
SRC=${3:-}

printf '%s' "$D" | grep -Eq '^([a-z0-9]([a-z0-9-]*[a-z0-9])?\.)+[a-z]{2,}$' ||
    die "invalid domain name '$D'"
case "$D" in
    example.*|*.example.*) die "'$D' is a documentation name; copy example.com.dns to <your-domain>.dns" ;;
esac

ZONES_D=$(dirname "$BIND_CONF")/zones.d
ZONE_FILE=$BIND_ZONE_DIR/$D.zone
DOMAINS=/etc/vps-mcp/domains
BACKUP_DIR=/etc/vps-mcp/zones

# Containers whose hostname belongs to $D (apex or one label below).
containers_of() {
    podman ps -a --format '{{.Names}}' 2>/dev/null | sed -n 's/-web$//p' |
        awk -v d="$D" '$0 == d || (substr($0, length($0) - length(d)) == "." d && index(substr($0, 1, length($0) - length(d) - 1), ".") == 0)'
}

# named.conf.local includes every zone statement in zones.d (BIND has no glob).
regen_named_conf() {
    {
        echo "// Generated by multidomain/scripts/zone.sh — do not edit."
        for f in "$ZONES_D"/*.conf; do
            [ -e "$f" ] && echo "include \"$f\";"
        done
    } > "$BIND_CONF"
    chgrp named "$BIND_CONF" 2>/dev/null || chgrp bind "$BIND_CONF" 2>/dev/null || true
    chmod 640 "$BIND_CONF"
}

case "$MODE" in
apply)
    [ -f "$SRC" ] || die "records file '$SRC' not found (start from example.com.dns)"

    # ── validate the records file ───────────────────────────────────────────
    owners=$(mktemp)
    trap 'rm -f "$owners"' EXIT
    awk '
        function bad(msg) { printf "%s:%d: %s\n", FILENAME, NR, msg; err = 1 }
        {
            line = $0; sub(/;.*/, "", line)
            if (line ~ /^[ \t]*$/) next
            if (depth == 0) {
                if (line ~ /^\$/)       bad("$-directives are not allowed")
                else if (line ~ /^[ \t]/) bad("owner name required (no leading whitespace)")
                n = split(line, f, /[ \t]+/); owner = tolower(f[1]); type = ""
                for (i = 2; i <= n; i++) {
                    u = toupper(f[i])
                    if (u ~ /^[0-9]+$/ || u == "IN") continue
                    type = u; break
                }
                if (type == "SOA" || type == "NS") bad(type " records are host-managed")
                if (owner ~ /(^|\.)mail\._domainkey(\.|$)/) bad("mail._domainkey is host-managed (DKIM)")
                if (type == "A" || type == "AAAA" || type == "CNAME") print owner > "/dev/stderr"
            }
            depth += gsub(/\(/, "(", line) - gsub(/\)/, ")", line)
        }
        END { exit err }
    ' "$SRC" 2> "$owners" || exit 1
    for c in $(containers_of); do
        while read -r o; do
            case "$o" in
                @) fq=$D ;;
                *.) fq=${o%.} ;;
                *) fq=$o.$D ;;
            esac
            [ "$fq" != "$c" ] || die "$SRC: '$o' is served by container $c-web; remove that A/AAAA/CNAME record"
        done < "$owners"
    done

    # ── DKIM key + opendkim tables ──────────────────────────────────────────
    mkdir -p /etc/opendkim/keys/"$D"
    if [ ! -f /etc/opendkim/keys/"$D"/mail.private ]; then
        opendkim-genkey -b 2048 -D /etc/opendkim/keys/"$D"/ -d "$D" -s mail
        chown -R opendkim:opendkim /etc/opendkim/keys
    fi
    dkim_changed=
    touch /etc/opendkim/KeyTable /etc/opendkim/SigningTable
    grep -q "^$D " /etc/opendkim/KeyTable || {
        echo "$D $D:mail:/etc/opendkim/keys/$D/mail.private" >> /etc/opendkim/KeyTable; dkim_changed=1; }
    grep -qxF "*@$D $D" /etc/opendkim/SigningTable || {
        printf '*@%s %s\n*@*.%s %s\n' "$D" "$D" "$D" "$D" >> /etc/opendkim/SigningTable; dkim_changed=1; }

    # ── build and check the zone ────────────────────────────────────────────
    today=$(date +%Y%m%d)01
    old=$(awk '/SOA/ { s = 1 } s && $1 ~ /^[0-9]+$/ { print $1; exit }' "$ZONE_FILE" 2>/dev/null || true)
    serial=$today
    [ -n "$old" ] && [ "$old" -ge "$serial" ] && serial=$((old + 1))

    tmp=$(mktemp "$BIND_ZONE_DIR/.$D.zone.XXXXXX")
    trap 'rm -f "$owners" "$tmp"' EXIT
    {
        sed -e "s|__IP__|$IP|g" \
            -e "s|__DOMAIN__|$D|g" \
            -e "s|__NS1__|${NS1:-ns1.$D}|g" \
            -e "s|__SERIAL__|$serial|g" \
            host/bind/zone.tmpl
        echo
        echo "; ── DKIM (host-managed) ──"
        cat /etc/opendkim/keys/"$D"/mail.txt
        echo
        echo "; ── $SRC (operator-managed) ──"
        cat "$SRC"
    } > "$tmp"
    named-checkzone "$D" "$tmp" || die "zone check failed; live zone left unchanged"

    chgrp named "$tmp" 2>/dev/null || chgrp bind "$tmp" 2>/dev/null || true
    chmod 640 "$tmp"
    mv "$tmp" "$ZONE_FILE"

    # ── register: zone statement, domain list, backup ───────────────────────
    mkdir -p "$ZONES_D"
    sed -e "s|__DOMAIN__|$D|g" -e "s|__BIND_ZONE_DIR__|$BIND_ZONE_DIR|g" \
        host/bind/named.conf.local.tmpl > "$ZONES_D/$D.conf"
    chgrp named "$ZONES_D/$D.conf" 2>/dev/null || chgrp bind "$ZONES_D/$D.conf" 2>/dev/null || true
    chmod 640 "$ZONES_D/$D.conf"
    regen_named_conf
    touch "$DOMAINS"
    grep -qxF "$D" "$DOMAINS" || echo "$D" >> "$DOMAINS"
    mkdir -p "$BACKUP_DIR"
    cp "$SRC" "$BACKUP_DIR/$D.dns"

    rndc reconfig
    rndc reload "$D"
    rndc notify "$D" 2>/dev/null || true
    [ -z "$dkim_changed" ] || systemctl restart opendkim
    echo "$D: zone serial $serial is live."
    ;;

remove)
    cs=$(containers_of)
    [ -z "$cs" ] || die "containers still use $D: $(echo $cs | sed 's/ /-web /g')-web — remove them first"
    rm -f "$ZONES_D/$D.conf" "$ZONE_FILE"
    regen_named_conf
    [ ! -f "$DOMAINS" ] || sed -i "/^$(printf '%s' "$D" | sed 's/\./\\./g')\$/d" "$DOMAINS"
    for t in KeyTable SigningTable; do
        [ -f /etc/opendkim/$t ] || continue
        awk -v d="$D" '$1 != d && $2 != d' /etc/opendkim/$t > /etc/opendkim/$t.new
        mv /etc/opendkim/$t.new /etc/opendkim/$t
    done
    [ ! -f "$BACKUP_DIR/$D.dns" ] || mv "$BACKUP_DIR/$D.dns" "$BACKUP_DIR/$D.dns.removed"
    rndc reconfig
    systemctl restart opendkim
    echo "$D: zone removed (DKIM key kept in /etc/opendkim/keys/$D)."
    ;;

*)
    die "usage: zone.sh apply <domain> <records-file> | remove <domain>"
    ;;
esac
